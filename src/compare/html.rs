    // ── escape_html ────────────────────────────────────────────────────

    #[test]
    fn escape_html_escapes_all_five_characters() {
        let s = "a&b<c>d\"e'f";
        let esc = escape_html(s);
        assert!(esc.contains("&amp;"));
        assert!(esc.contains("&lt;"));
        assert!(esc.contains("&gt;"));
        assert!(esc.contains("&quot;"));
        assert!(esc.contains("&#39;"));
        assert!(!esc.contains("<c>"));
        assert!(!esc.contains("\"e"));
    }

    #[test]
    fn escape_html_passes_through_unicode() {
        let s = "α β γ δ";
        let esc = escape_html(s);
        assert_eq!(esc, s);
    }

    #[test]
    fn escape_html_neutralises_xss_payload() {
        // Exact payload an attacker would put in a gene ID column.
        let payload = "<script>alert('xss')</script>";
        let esc = escape_html(payload);
        assert!(!esc.contains("<script"));
        assert!(esc.contains("&lt;script"));
    }

    // ── render_html_report ─────────────────────────────────────────────

    #[test]
    fn render_html_report_produces_non_empty_output() {
        let dir = tempfile::tempdir().unwrap();
        let out = dir.path().join("report.html");
        let inputs = fixture_inputs();
        let counts = vec![1000, 1100, 1200];
        let ogs = fixture_orthogroups();
        let summary = fixture_summary();
        render_html_report(
            &out,
            &inputs,
            &counts,
            &ogs,
            &summary,
            Some("(genome_a:0.1,(genome_b:0.05,genome_c:0.05):0.02);"),
            "myconote-cli compare a.gff3 a.fa b.gff3 b.fa c.gff3 c.fa --html",
            &[],
        )
        .unwrap();
        let body = std::fs::read_to_string(&out).unwrap();
        assert!(body.len() > 1000, "report too small: {} bytes", body.len());
        // Skeleton sanity.
        assert!(body.contains("<!DOCTYPE html>"));
        assert!(body.contains("MycoNote-CLI compare report"));
        // Spec compliance: panel labels.
        assert!(body.contains("Pan-genome shape"));
        assert!(body.contains("Per-genome statistics"));
        assert!(body.contains("Ortholog table"));
        assert!(body.contains("Species tree"));
        // CSS / JS embedded.
        assert!(body.contains("--col-core:"));
        assert!(body.contains("attachSort"));
        // Genome names rendered.
        assert!(body.contains("genome_a"));
        assert!(body.contains("genome_b"));
        assert!(body.contains("genome_c"));
        // No external assets.
        assert!(
            !body.contains("https://"),
            "report must not load external resources"
        );
        assert!(
            !body.contains("<link"),
            "report must not <link> external CSS"
        );
    }

