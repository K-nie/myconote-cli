//! Self-contained HTML report for `myconote-cli compare --html`.
//!
//! Produces `compare_out/report.html`: a single HTML file that opens
//! correctly from `file://` with no network access. CSS and JS are
//! embedded via `include_str!` so no external assets ever load. The
//! report carries:
//!
//!   1. Pan-genome summary (core / soft-core / shell / cloud / singleton
//!      counts as a styled table plus a stacked-bar SVG).
//!   2. Per-genome stats (n_proteins, n_orthogroups, % core, % singletons).
//!   3. Sortable ortholog table with a client-side text filter.
//!   4. Inline-SVG species tree from OrthoFinder's rooted Newick.
//!   5. Reproducibility footer (tool versions, run command, input
//!      checksums) so the report itself documents what produced it.
//!
//! No askama, no handlebars, no React. Vanilla HTML built by
//! `tinytemplate` plus a small Newick → SVG renderer below.

