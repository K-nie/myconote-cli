    #[test]
    fn per_genome_stats_three_genome_fixture() {
        let inputs = fixture_inputs();
        let counts = vec![1000, 1100, 1200];
        let ogs = fixture_orthogroups();
        let stats = compute_per_genome_stats(&inputs, &counts, &ogs);
        assert_eq!(stats.len(), 3);
        // genome_a is in 2/2 of its orthogroups; one is core, one is
        // singleton → 50% core, 50% singleton.
        let a = stats.iter().find(|s| s.name == "genome_a").unwrap();
        assert_eq!(a.n_orthogroups, 2);
        assert_eq!(a.n_proteins, 1000);
        assert!((a.pct_in_core - 50.0).abs() < 1e-9);
        assert!((a.pct_singletons - 50.0).abs() < 1e-9);
        // genome_b is in 1/2 (only the core one).
        let b = stats.iter().find(|s| s.name == "genome_b").unwrap();
        assert_eq!(b.n_orthogroups, 1);
        assert!((b.pct_in_core - 100.0).abs() < 1e-9);
    }
