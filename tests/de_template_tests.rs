// ── Live R syntactic validation (ignored unless Rscript is on PATH) ────────

#[test]
#[ignore]
fn de_template_emits_syntactically_valid_r() {
    if which::which("Rscript").is_err() {
        eprintln!("Rscript not on PATH — skipping");
        return;
    }

    let tmp = TempDir::new().unwrap();
    let quant_dir = tmp.path().join("quant_out");
    write_fake_quant_dir(&quant_dir);
    let out = tmp.path().join("analysis.R");

    bin()
        .arg("de-template")
        .arg("--quant-dir")
        .arg(&quant_dir)
        .arg("--design")
        .arg("~ condition")
        .arg("--contrast")
        .arg("condition,treated,control")
        .arg("-o")
        .arg(&out)
        .assert()
        .success();

    // `Rscript -e 'parse(...)'` returns nonzero on syntax error
    // *and* prints the failure location. A zero-exit run is our
    // success signal; we don't care about the stdout.
    let status = std::process::Command::new("Rscript")
        .arg("--vanilla")
        .arg("-e")
        .arg(format!("invisible(parse(file = \"{}\"))", out.display()))
        .status()
        .expect("Rscript invocation");
    assert!(
        status.success(),
        "emitted R script is not syntactically valid: {}",
        out.display()
    );
}
